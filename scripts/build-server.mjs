// Bundles server/main.ts into dist-gas/Code.js for Apps Script.
//
// esbuild wraps everything in an IIFE, so internal helpers are invisible to
// google.script.run. Only the functions listed in PUBLIC_FUNCTIONS get a top-level
// wrapper; those are the only ones a browser (or trigger) can call.

import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readdirSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const PUBLIC_FUNCTIONS = ['doGet', 'getDashboardData', 'getOpsData', 'refreshCache', 'installTriggers', 'checkSetup'];

const footer = PUBLIC_FUNCTIONS.map((name) => `function ${name}(e) { return KiwimbiServer.${name}(e); }`).join('\n');

/**
 * A fingerprint of the server-side code. The server's cache keys include it, so a new
 * release never reads data cached by an older one (whose shape may differ).
 */
export function codeFingerprint() {
  const hash = createHash('sha256');
  for (const dir of ['server', 'shared']) {
    for (const f of readdirSync(resolve(root, dir)).filter((n) => n.endsWith('.ts')).sort()) {
      hash.update(`${dir}/${f}
`).update(readFileSync(resolve(root, dir, f)));
    }
  }
  return hash.digest('hex').slice(0, 10);
}

/** Returns the bundled Apps Script source as a string. */
export async function bundleServer() {
  const result = await build({
    entryPoints: [resolve(root, 'server/main.ts')],
    bundle: true,
    write: false,
    format: 'iife',
    globalName: 'KiwimbiServer',
    target: 'es2019',
    platform: 'neutral',
    charset: 'utf8',
    legalComments: 'none',
    define: { __CODE_VERSION__: JSON.stringify(codeFingerprint()) },
    banner: { js: '// Kiwimbi dashboard server. Generated by scripts/build-server.mjs from server/*.ts. Do not edit.\n// This file contains code only; data is read from the sheet at run time.' },
    footer: { js: footer },
    logLevel: 'silent',
  });
  return result.outputFiles[0].text;
}

async function main() {
  const { writeFileSync } = await import('node:fs');
  const out = resolve(root, 'dist-gas');
  mkdirSync(out, { recursive: true });
  writeFileSync(resolve(out, 'Code.js'), await bundleServer());
  copyFileSync(resolve(root, 'server/appsscript.json'), resolve(out, 'appsscript.json'));
  console.log('Built dist-gas/Code.js and dist-gas/appsscript.json');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
